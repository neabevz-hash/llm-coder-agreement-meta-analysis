"""Manuscript tables from the analysis results and the extraction tables (no numbers typed by hand).

Writes manuscript/tables.md: Table 1 study characteristics, Table 2 pooled agreement by task type with GRADE,
Table 3 hypotheses G1-G10 and post hoc findings, Table 4 sensitivity analyses; and manuscript/supplement_S1_studies.csv
(included studies with their reports, task types and risk of bias).
Run: .venv/Scripts/python.exe -I papers/llm-coder-agreement-meta/analysis/tables.py
"""
from __future__ import annotations

import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

PAPER = Path(__file__).resolve().parent.parent
RES = PAPER / "analysis" / "results"
OUT = PAPER / "manuscript"
TT = {"T1": "T1 codebook coding", "T2": "T2 assessment scoring", "T3": "T3 clinical state rating",
      "T4": "T4 LLM-as-a-judge", "all": "All tasks"}


def rows(path: Path) -> list[dict]:
    return list(csv.DictReader(path.open(encoding="utf-8")))


def f2(x, d=2) -> str:
    try:
        v = float(x)
    except (TypeError, ValueError):
        return "–"
    return f"{v:.{d}f}".replace("-", "−")


def pval(x) -> str:
    try:
        v = float(x)
    except (TypeError, ValueError):
        return "–"
    return "< .001" if v < 0.001 else f"{v:.3f}".lstrip("0").replace("-", "−")


def ci(r, lo="ci_lb", hi="ci_ub") -> str:
    return f"[{f2(r[lo])}, {f2(r[hi])}]"


def pct(n, d) -> str:
    return f"{n} ({100 * n / d:.0f}%)" if d else "–"


def main():
    st = [s for s in rows(PAPER / "forms" / "studies.csv") if not s["excluded_r1"]]
    ids = {s["study_id"] for s in st}
    tasks = [t for t in rows(PAPER / "forms" / "tasks.csv") if t["study_id"] in ids and not t["excluded_r1"]]
    est = [e for e in rows(PAPER / "forms" / "estimates.csv") if e["study_id"] in ids and e["include"] == "yes"]
    hr = [h for h in rows(PAPER / "forms" / "human_reliability.csv") if h["study_id"] in ids]
    types = defaultdict(set)
    for t in tasks:
        types[t["study_id"]].add(t["task_type"])
    out = ["# Tables (generated by analysis/tables.py; do not edit by hand)\n"]

    # Table 1
    n = len(st)
    by = lambda key, vals: Counter(v for s in st for v in vals(s))
    tt = Counter(t for s in st for t in types[s["study_id"]])
    first = lambda field: Counter(Counter(t[field] for t in tasks if t["study_id"] == s["study_id"]).most_common(1)[0][0]
                                  for s in st if any(t["study_id"] == s["study_id"] for t in tasks))
    pub = Counter(s["pub_status"] for s in st)
    field = Counter(s["field"] for s in st)
    text_type, source = first("text_type"), first("text_source")
    lang = first("language")
    expert, ref = first("human_expertise"), first("reference_type")
    years = Counter(s["year"] for s in st)
    gen = Counter(e["generation"] or "not dated (ensembles, unnamed)" for e in est
                  if e["outcome"] in ("primary", "secondary") and e["pool"] == "yes")
    out += ["## Table 1. Characteristics of the included studies\n",
            f"{n} studies ({sum(len(s['report_ids'].split(';')) for s in st)} reports). A study can contribute several task types.\n",
            "| Characteristic | Studies, n (%) |", "| --- | --- |"]
    for k in ("T1", "T2", "T3", "T4"):
        out.append(f"| {TT[k]} | {pct(tt[k], n)} |")
    for label, c in [("Publication status", pub), ("Authors' field", field), ("Main text type", text_type),
                     ("Texts real or synthetic (main task)", source), ("Language of texts (main task)", lang),
                     ("Human coders (main task)", expert), ("Human reference (main task)", ref), ("Publication year", years)]:
        out.append(f"| **{label}** | |")
        top = c.most_common(8)
        for v, k in top:
            out.append(f"| {v or 'not reported'} | {pct(k, n)} |")
        rest = sum(c.values()) - sum(k for _, k in top)
        if rest:
            out.append(f"| remaining categories | {pct(rest, n)} |")
    hr_st = len({h['study_id'] for h in hr})
    out += [f"| **Human–human agreement reported** | {pct(hr_st, n)} |",
            "", "Model generation of the pooled estimates (kappa family, ICC and correlations):", ""]
    out += [f"- {g}: {k}" for g, k in gen.most_common()]

    # Table 2
    gr = {r["analysis"]: r for r in rows(RES / "grade.csv")}
    out += ["", "## Table 2. Pooled agreement between LLMs and the human reference, by task type\n",
            "CHE model, CR2 95% CI; prediction interval truncated at 1. I² for studies / estimates within studies (%).\n",
            "| Outcome | Task type | Studies | Estimates | Pooled | 95% CI | 95% PI | I² study / estimate | Certainty (GRADE) |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for name, f in [("Kappa family", "rq1_pooled_kappa.csv"), ("ICC and correlations", "rq1_pooled_icc_r.csv")]:
        for r in rows(RES / f):
            g = gr.get(r["analysis"], {}).get("certainty", "–") if name == "Kappa family" else "not rated"
            out.append(f"| {name} | {TT[r['analysis']]} | {r['k_studies']} | {r['k_estimates']} | {f2(r.get('est'))} | "
                       f"{ci(r)} | [{f2(r.get('pi_lb'))}, {f2(r.get('pi_ub'))}] | {f2(r.get('i2_study'), 0)} / "
                       f"{f2(r.get('i2_estimate'), 0)} | {g} |")

    # Table 3
    g1 = {r["analysis"]: r for r in rows(RES / "g1_delta_kappa.csv")}
    mods = rows(RES / "moderators.csv") + rows(RES / "g3_release.csv")
    w3 = rows(RES / "g3_within_study.csv")[0]
    g8 = rows(RES / "g8.csv")[0]
    out += ["", "## Table 3. Hypotheses\n",
            "| Hypothesis | Test | Studies | Estimate [95% CI] | p (CR2) | Result |", "| --- | --- | --- | --- | --- | --- |"]
    m = g1["delta kappa, matched"]
    out.append(f"| G1a human ceiling | Δκ = LLM–human κ − human–human κ, matched comparisons | {m['k_studies']} | "
               f"{f2(m['est'])} {ci(m)} | – | {'supported' if float(m['ci_ub']) < 0 else 'not supported'} |")
    b = next((r for k, r in g1.items() if k.startswith("G1b")), None)
    if b and b.get("est"):
        out.append(f"| G1b equivalence, models from 2025 | 90% CI of Δκ within ±0.10 | {b['k_studies']} | "
                   f"{f2(b['est'])} [{f2(b['ci90_lb'])}, {f2(b['ci90_ub'])}] (90% CI) | – | "
                   f"{'supported' if b['equivalent_within_0.10'] == 'TRUE' else 'not supported'} |")

    def mrow(label, mod, term, if_null="not supported"):
        r = next((x for x in mods if x["moderator"].startswith(mod) and x["term"] == term), None)
        if r is None:
            return f"| {label} | {mod} | – | – | – | fewer than 10 studies |"
        rel = "" if r.get("reliable") in ("TRUE", "True") else " (df < 4, unreliable)"
        res = "supported" if float(r["p"]) < 0.05 else if_null
        return (f"| {label} | {mod}: {term} | {r['k_studies']} | {f2(r['b'])} [{f2(r['ci_lb'])}, {f2(r['ci_ub'])}] | "
                f"{pval(r['p'])}{rel} | {res} |")
    out += [mrow("G2 shared difficulty", "human-human kappa (G2)", "hh"),
            mrow("G3 model generations", "release date, years since 2020-06 (G3)", "years"),
            mrow("G3 reasoning models", "reasoning model (G3)", "reasoning_modelyes",
                 "no difference (consistent with 'at least as well')"),
            f"| G3 within studies | newest minus oldest model, same units | {w3['k_studies']} | {f2(w3['est'])} {ci(w3)} | – | "
            f"{'not supported' if float(w3['ci_lb']) <= 0 else 'supported'} |",
            mrow("G4 task type", "task type (G4)", "task_typeT4"),
            mrow("G4 construct type", "construct type (G4)", "construct_typemanifest"),
            mrow("G5 prompting", "prompting (G5)", "promptfew-shot"),
            mrow("G5 fine-tuning", "prompting (G5)", "promptfine-tuned"),
            mrow("G6 categories", "log number of categories (G6)", "log_cat"),
            mrow("G7 reference", "reference: aggregate vs single coder (G7)", "ref2single coder"),
            f"| G8 rare codes | observed agreement − κ, same configuration | {g8['k_studies']} | {f2(g8['est'])} {ci(g8)} | – | "
            f"{'supported' if float(g8['ci_lb']) > 0 else 'not supported'} |",
            mrow("G9 selective reporting", "configurations reported (G9)", "selbest only"),
            mrow("G10 language", "language (G10)", "englishother"),
            mrow("Post hoc: contamination", "contamination (risk of bias 4)", "rob4low"),
            mrow("Post hoc: open weights", "open weights", "openyes"),
            mrow("Post hoc: synthetic texts", "real vs synthetic texts", "srcsynthetic"),
            mrow("Post hoc: human expertise", "human expertise", "experttrained-coder"),
            mrow("Post hoc: peer review", "peer-reviewed", "peerTRUE")]

    # Table 4
    out += ["", "## Table 4. Sensitivity analyses (kappa family)\n",
            "| Analysis | Studies | Estimates | Pooled κ [95% CI] |", "| --- | --- | --- | --- |"]
    for r in rows(RES / "sensitivity.csv"):
        na = lambda x: "–" if x in (None, "", "NA") else x
        out.append(f"| {r['analysis']} | {na(r.get('k_studies'))} | {na(r.get('k_estimates'))} | "
                   f"{f2(r.get('est'))} {ci(r)} |")
    eg = rows(RES / "small_study_effects.csv")
    out += ["", "Small-study effects (SE as moderator, CR2): " + "; ".join(
        f"{TT[r['subset']]}: slope {f2(r.get('slope_se'))}, p {pval(r.get('p'))}" for r in eg if r.get("slope_se") not in (None, "", "NA"))]
    OUT.mkdir(exist_ok=True)
    (OUT / "tables.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")

    # Supplement S1
    with (OUT / "supplement_S1_studies.csv").open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["study_id", "first_author", "year", "title", "doi", "reports", "task_types", "pub_status",
                    "rob_1", "rob_2", "rob_3", "rob_4", "rob_5"])
        for s in st:
            w.writerow([s["study_id"], s["first_author"], s["year"], s["title"], s["doi"], s["report_ids"],
                        "; ".join(sorted(types[s["study_id"]])), s["pub_status"], *(s[f"rob_{i}"] for i in range(1, 6))])
    print(f"manuscript/tables.md and supplement_S1_studies.csv ({n} studies)")


if __name__ == "__main__":
    main()
